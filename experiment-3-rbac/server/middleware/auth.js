const jwt = require('jsonwebtoken');

/**
 * ============================================================================
 * JWT (JSON Web Token) Structure Explanation:
 * 
 * A JWT is a compact, URL-safe string composed of three Base64URL-encoded parts
 * separated by dots (.):  HEADER.PAYLOAD.SIGNATURE
 * 
 * 1. HEADER (Base64Url encoded):
 *    Contains metadata about the token format and cryptographic algorithm.
 *    Example: { "alg": "HS256", "typ": "JWT" }
 * 
 * 2. PAYLOAD (Base64Url encoded):
 *    Contains the claims/data (e.g., userId, email, role, issue time 'iat', expiration 'exp').
 *    Example: { "id": 1, "email": "admin@app.com", "role": "admin", "exp": 1723456789 }
 * 
 * 3. SIGNATURE:
 *    A cryptographic signature generated by hashing:
 *    HMACSHA256(base64UrlEncode(header) + "." + base64UrlEncode(payload), secret)
 *    This prevents tampering; if any payload byte is altered, the signature becomes invalid.
 * ============================================================================
 */

/**
 * Middleware: verifyToken
 * Validates the short-lived Access Token sent in the 'Authorization: Bearer <token>' header.
 * If valid, decodes the payload and attaches it to `req.user`.
 * If expired or invalid, responds with 401 Unauthorized so Axios interceptor can refresh it.
 */
const verifyToken = (req, res, next) => {
  const authHeader = req.headers['authorization'] || req.headers['Authorization'];

  if (!authHeader || !authHeader.startsWith('Bearer ')) {
    return res.status(401).json({
      success: false,
      message: 'Access Denied: No Bearer token provided in Authorization header.'
    });
  }

  const token = authHeader.split(' ')[1];

  jwt.verify(token, process.env.ACCESS_TOKEN_SECRET, (err, decoded) => {
    if (err) {
      // Token is either expired (TokenExpiredError) or corrupted (JsonWebTokenError)
      return res.status(401).json({
        success: false,
        isTokenExpired: err.name === 'TokenExpiredError',
        message: err.name === 'TokenExpiredError' 
          ? 'Access token has expired. Please refresh your session.' 
          : 'Invalid access token.'
      });
    }

    // Attach decoded user payload (id, email, role, permissions) to request object
    req.user = decoded;
    next();
  });
};

/**
 * Middleware: authorizeRoles
 * Role-Based Access Control (RBAC) Guard.
 * Checks whether the authenticated user's role is included in the allowed roles list.
 * 
 * @param  {...string} allowedRoles - e.g. authorizeRoles('Admin', 'Editor')
 */
const authorizeRoles = (...allowedRoles) => {
  return (req, res, next) => {
    if (!req.user || !req.user.role) {
      return res.status(403).json({
        success: false,
        message: 'Forbidden: User role not found in authentication context.'
      });
    }

    if (!allowedRoles.map(r => r.toLowerCase()).includes(req.user.role.toLowerCase())) {
      return res.status(403).json({
        success: false,
        message: `Forbidden: Your role (${req.user.role}) is not authorized to access this resource. Allowed roles: ${allowedRoles.join(', ')}`
      });
    }

    next();
  };
};

module.exports = {
  verifyToken,
  authorizeRoles
};
